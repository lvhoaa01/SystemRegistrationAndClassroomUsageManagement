  TrangThai VARCHAR(16) NOT NULL,
  TongPhaiTra DECIMAL(14,2) NOT NULL,
  DaThanhToan DECIMAL(14,2) NOT NULL DEFAULT 0,
  DaHoan DECIMAL(14,2) NOT NULL DEFAULT 0,
  TienTe CHAR(3) NOT NULL DEFAULT 'VND',
  Provider VARCHAR(24) NULL,
  IdempotencyKey CHAR(36) NULL,
  ProviderReference VARCHAR(100) NULL,
  SoLanThu SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  MaLoiCuoi VARCHAR(80) NULL,
  XuLyLuc DATETIME(6) NULL,
  HoanTienIdempotencyKey CHAR(36) NULL,
  TrangThaiHoanTien VARCHAR(16) NOT NULL DEFAULT 'NONE',
  ProviderRefundReference VARCHAR(100) NULL,
  LyDoHoanTien VARCHAR(500) NULL,
  HoanTienHoanTatLuc DATETIME(6) NULL,
  TaoLuc DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  CapNhatLuc DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
