  PhongID BIGINT UNSIGNED NOT NULL,
  TietBatDau TINYINT UNSIGNED NOT NULL,
  TietKetThuc TINYINT UNSIGNED NOT NULL,
  LoaiHoatDong ENUM('LICH_HOC','LICH_THI','SU_KIEN','BAN_NGOAI_KHOA') NOT NULL,
  LopHocPhanID BIGINT UNSIGNED NULL,
  GiangVienID BIGINT UNSIGNED NULL,
  SiSo SMALLINT UNSIGNED NULL,
  TenHoatDong VARCHAR(200) NOT NULL,
  LoaiBuoi ENUM('LY_THUYET','THUC_HANH','THI','SU_KIEN','KHAC') NOT NULL,
  GhiChu VARCHAR(500) NULL,
  TrangThai ENUM('NHAP','HOAT_DONG','BI_THAY_THE','DA_GIAI_PHONG','CAN_BO_TRI_LAI') NOT NULL,
  LyDoCanBoTriLai VARCHAR(500) NULL,
  CONSTRAINT uq_lich_dotimport_madong UNIQUE (DotImportLichID, MaDong),
  CONSTRAINT fk_lich_dotimport FOREIGN KEY (DotImportLichID) REFERENCES DotImportLich(DotImportLichID) ON DELETE RESTRICT,
  CONSTRAINT fk_lich_phong FOREIGN KEY (PhongID) REFERENCES Phong(PhongID) ON DELETE RESTRICT,
