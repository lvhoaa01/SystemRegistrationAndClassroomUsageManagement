CREATE TABLE LopHocPhan (
  LopHocPhanID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  HocKyID BIGINT UNSIGNED NOT NULL,
  HocPhanID BIGINT UNSIGNED NOT NULL,
  MaLopHocPhan VARCHAR(50) NOT NULL,
  MaNhomSinhVien VARCHAR(100) NOT NULL,
  SiSo SMALLINT UNSIGNED NOT NULL,
  SoBuoiMoiTuan TINYINT UNSIGNED NOT NULL,
  SoTietMoiBuoi TINYINT UNSIGNED NOT NULL,
  SoTuanDay TINYINT UNSIGNED NOT NULL,
  LoaiBuoiMacDinh ENUM('LY_THUYET','THUC_HANH') NOT NULL,
