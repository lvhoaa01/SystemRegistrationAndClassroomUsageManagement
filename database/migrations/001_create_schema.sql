CREATE TABLE NguoiDung (
  NguoiDungID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  MaNguoiDung VARCHAR(30) NOT NULL,
  HoTen VARCHAR(150) NOT NULL,
  Email VARCHAR(150) NULL,
  MatKhauHash VARCHAR(255) NOT NULL,
  VaiTro ENUM('GIANG_VIEN','QUAN_LY','ADMIN') NOT NULL,
  LaGiangVien BOOLEAN NOT NULL DEFAULT FALSE,
  TrangThaiGiangDay ENUM('DANG_DAY','TAM_VANG','KHONG_AP_DUNG') NOT NULL,
  TrangThaiTaiKhoan ENUM('HOAT_DONG','BI_KHOA') NOT NULL DEFAULT 'HOAT_DONG',
  TaoLuc DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  CapNhatLuc DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  CONSTRAINT uq_nguoidung_ma UNIQUE (MaNguoiDung),
  CONSTRAINT uq_nguoidung_email UNIQUE (Email),
  CONSTRAINT ck_nguoidung_giangday CHECK (
    (LaGiangVien = TRUE AND TrangThaiGiangDay IN ('DANG_DAY','TAM_VANG'))
    OR (LaGiangVien = FALSE AND TrangThaiGiangDay = 'KHONG_AP_DUNG')
  )
) ENGINE=InnoDB;

CREATE TABLE ToaNha (
  ToaNhaID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  MaToa VARCHAR(20) NOT NULL,
  TenToa VARCHAR(100) NOT NULL,
  TrangThai ENUM('HOAT_DONG','NGUNG_SU_DUNG') NOT NULL DEFAULT 'HOAT_DONG',
  CONSTRAINT uq_toanha_ma UNIQUE (MaToa)
) ENGINE=InnoDB;

CREATE TABLE Phong (
  PhongID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ToaNhaID BIGINT UNSIGNED NOT NULL,
  MaPhong VARCHAR(30) NOT NULL,
  Tang SMALLINT NOT NULL,
  TenPhong VARCHAR(100) NULL,
  LoaiPhong ENUM('LY_THUYET','THUC_HANH','KHAC') NOT NULL,
  SucChua SMALLINT UNSIGNED NOT NULL,
  ChoPhepDat BOOLEAN NOT NULL DEFAULT FALSE,
  TrangThai ENUM('HOAT_DONG','TAM_NGUNG','NGUNG_SU_DUNG') NOT NULL DEFAULT 'HOAT_DONG',
  GhiChu VARCHAR(500) NULL,
  CONSTRAINT uq_phong_ma UNIQUE (MaPhong),
  CONSTRAINT fk_phong_toanha FOREIGN KEY (ToaNhaID) REFERENCES ToaNha(ToaNhaID) ON DELETE RESTRICT,
  CONSTRAINT ck_phong_succhua CHECK (SucChua > 0),
  INDEX idx_phong_search (TrangThai, ChoPhepDat, LoaiPhong, SucChua)
) ENGINE=InnoDB;

CREATE TABLE ThietBi (
  ThietBiID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  MaThietBi VARCHAR(30) NOT NULL,
  TenThietBi VARCHAR(100) NOT NULL,
  DonViTinh VARCHAR(30) NOT NULL,
  TrangThai ENUM('HOAT_DONG','NGUNG_SU_DUNG') NOT NULL DEFAULT 'HOAT_DONG',
  CONSTRAINT uq_thietbi_ma UNIQUE (MaThietBi)
) ENGINE=InnoDB;

CREATE TABLE PhongThietBi (
  PhongID BIGINT UNSIGNED NOT NULL,
  ThietBiID BIGINT UNSIGNED NOT NULL,
  SoLuongTot SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  SoLuongHong SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  CapNhatLuc DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (PhongID, ThietBiID),
  CONSTRAINT fk_phongthietbi_phong FOREIGN KEY (PhongID) REFERENCES Phong(PhongID) ON DELETE RESTRICT,
  CONSTRAINT fk_phongthietbi_thietbi FOREIGN KEY (ThietBiID) REFERENCES ThietBi(ThietBiID) ON DELETE RESTRICT,
  INDEX idx_phongthietbi_search (ThietBiID, SoLuongTot, PhongID)
) ENGINE=InnoDB;

CREATE TABLE HocKy (
  HocKyID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  MaHocKy VARCHAR(30) NOT NULL,
  TenHocKy VARCHAR(100) NOT NULL,
  NgayBatDau DATE NOT NULL,
  NgayKetThuc DATE NOT NULL,
  TrangThai ENUM('NHAP','MO_DAT_PHONG','DONG') NOT NULL DEFAULT 'NHAP',
  DotImportHienHanhID BIGINT UNSIGNED NULL,
  SoGioBaoTruocTuDong SMALLINT UNSIGNED NOT NULL DEFAULT 24,
  SoNgayDatTruocToiDa SMALLINT UNSIGNED NOT NULL DEFAULT 30,
  SoTietToiDaMoiPhieu TINYINT UNSIGNED NOT NULL DEFAULT 5,
  SoPhieuHoatDongToiDaMoiGV SMALLINT UNSIGNED NOT NULL DEFAULT 8,
  TuanTamNghi TINYINT UNSIGNED NULL DEFAULT 8,
  TuanThiCuoiKy TINYINT UNSIGNED NULL DEFAULT 13,
  CONSTRAINT uq_hocky_ma UNIQUE (MaHocKy),
  CONSTRAINT ck_hocky_ngay CHECK (NgayBatDau <= NgayKetThuc),
  CONSTRAINT ck_hocky_sotiet CHECK (SoTietToiDaMoiPhieu BETWEEN 1 AND 13)
) ENGINE=InnoDB;

CREATE TABLE KhungTiet (
  KhungTietID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  HocKyID BIGINT UNSIGNED NOT NULL,
  SoTiet TINYINT UNSIGNED NOT NULL,
  GioBatDau TIME NOT NULL,
  GioKetThuc TIME NOT NULL,
  Buoi ENUM('SANG','CHIEU','TOI') NOT NULL,
  CONSTRAINT uq_khungtiet_hocky_tiet UNIQUE (HocKyID, SoTiet),
  CONSTRAINT fk_khungtiet_hocky FOREIGN KEY (HocKyID) REFERENCES HocKy(HocKyID) ON DELETE RESTRICT,
  CONSTRAINT ck_khungtiet_so CHECK (SoTiet BETWEEN 1 AND 13),
  CONSTRAINT ck_khungtiet_gio CHECK (GioBatDau < GioKetThuc)
) ENGINE=InnoDB;

CREATE TABLE NgayNghi (
  NgayNghiID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  HocKyID BIGINT UNSIGNED NOT NULL,
  Ngay DATE NOT NULL,
  LyDo VARCHAR(255) NOT NULL,
  CONSTRAINT uq_ngaynghi_hocky_ngay UNIQUE (HocKyID, Ngay),
  CONSTRAINT fk_ngaynghi_hocky FOREIGN KEY (HocKyID) REFERENCES HocKy(HocKyID) ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE HocPhan (
  HocPhanID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  MaHocPhan VARCHAR(30) NOT NULL,
  TenHocPhan VARCHAR(150) NOT NULL,
  NhomDaoTao VARCHAR(50) NOT NULL,
  LoaiHocPhan ENUM('CHUYEN_NGANH','THONG_THUONG') NOT NULL,
  SoBuoiMoiTuanMacDinh TINYINT UNSIGNED NOT NULL DEFAULT 2,
  SoTietMoiBuoiMacDinh TINYINT UNSIGNED NOT NULL,
  SoTuanDayMacDinh TINYINT UNSIGNED NOT NULL DEFAULT 12,
  YeuCauThietBiJSON JSON NULL,
