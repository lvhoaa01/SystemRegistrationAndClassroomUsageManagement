  UNIQUE KEY UQ_SanPhamPhong_Ma (LoaiPhongID, MaSanPham),
  KEY IX_SanPhamPhong_PhongTrangThai (LoaiPhongID, TrangThai),
  CONSTRAINT FK_SanPhamPhong_Phong FOREIGN KEY (LoaiPhongID) REFERENCES LoaiPhong(LoaiPhongID),
