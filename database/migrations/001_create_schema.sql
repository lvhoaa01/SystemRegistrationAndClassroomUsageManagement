  CONSTRAINT CK_LoaiPhong_DienTich CHECK (DienTichM2 IS NULL OR DienTichM2 > 0),
  CONSTRAINT CK_LoaiPhong_TrangThai CHECK (TrangThai IN ('ACTIVE','INACTIVE'))
) ENGINE=InnoDB;

CREATE TABLE CoSoTienNghi (
  CoSoLuuTruID BIGINT UNSIGNED NOT NULL,
  TienNghiID BIGINT UNSIGNED NOT NULL,
