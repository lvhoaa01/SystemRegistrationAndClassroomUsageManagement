  CONSTRAINT CK_SanPhamPhong_ThanhToan CHECK (ThoiDiemThanhToan IN ('PAY_AT_PROPERTY','PAY_ONLINE')),
  CONSTRAINT CK_SanPhamPhong_TrangThai CHECK (TrangThai IN ('ACTIVE','INACTIVE'))
) ENGINE=InnoDB;

CREATE TABLE GiaPhongNgay (
  SanPhamPhongID BIGINT UNSIGNED NOT NULL,
  NgayLuuTru DATE NOT NULL,
  GiaCoBan DECIMAL(14,2) NOT NULL,
  DongBan TINYINT(1) NOT NULL DEFAULT 0,
  SoDemToiThieu TINYINT UNSIGNED NOT NULL DEFAULT 1,
  SoDemToiDa TINYINT UNSIGNED NULL,
  SoNgayDatTruoc SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  PhienBan INT UNSIGNED NOT NULL DEFAULT 1,
  CapNhatLuc DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (SanPhamPhongID, NgayLuuTru),
  KEY IX_GiaPhongNgay_Ngay (NgayLuuTru, DongBan, SanPhamPhongID),
  CONSTRAINT FK_GiaPhongNgay_SanPham FOREIGN KEY (SanPhamPhongID) REFERENCES SanPhamPhong(SanPhamPhongID),
  CONSTRAINT CK_GiaPhongNgay_Gia CHECK (GiaCoBan > 0),
  CONSTRAINT CK_GiaPhongNgay_SoDem CHECK (SoDemToiThieu BETWEEN 1 AND 30 AND (SoDemToiDa IS NULL OR (SoDemToiDa BETWEEN SoDemToiThieu AND 30))),
  CONSTRAINT CK_GiaPhongNgay_DatTruoc CHECK (SoNgayDatTruoc <= 730),
  CONSTRAINT CK_GiaPhongNgay_PhienBan CHECK (PhienBan >= 1)
) ENGINE=InnoDB;

CREATE TABLE KhuyenMai (
  KhuyenMaiID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  CoSoLuuTruID BIGINT UNSIGNED NOT NULL,
  MaKhuyenMai VARCHAR(24) NOT NULL,
  TenKhuyenMai VARCHAR(150) NOT NULL,
  PhanTramGiam DECIMAL(5,2) NOT NULL,
  DatTu DATETIME(6) NOT NULL,
  DatDen DATETIME(6) NOT NULL,
  LuuTruTu DATE NOT NULL,
  LuuTruDen DATE NOT NULL,
  TrangThai VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
  UNIQUE KEY UQ_KhuyenMai_Ma (CoSoLuuTruID, MaKhuyenMai),
  KEY IX_KhuyenMai_ApDung (CoSoLuuTruID, TrangThai, DatTu, DatDen, LuuTruTu, LuuTruDen),
  CONSTRAINT FK_KhuyenMai_CoSo FOREIGN KEY (CoSoLuuTruID) REFERENCES CoSoLuuTru(CoSoLuuTruID),
  CONSTRAINT CK_KhuyenMai_Giam CHECK (PhanTramGiam > 0 AND PhanTramGiam <= 100),
  CONSTRAINT CK_KhuyenMai_CuaSo CHECK (DatTu <= DatDen AND LuuTruTu <= LuuTruDen),
  CONSTRAINT CK_KhuyenMai_TrangThai CHECK (TrangThai IN ('ACTIVE','INACTIVE'))
) ENGINE=InnoDB;

CREATE TABLE TonPhongNgay (
  LoaiPhongID BIGINT UNSIGNED NOT NULL,
  NgayLuuTru DATE NOT NULL,
  TongSoLuong SMALLINT UNSIGNED NOT NULL,
  SoLuongDaGiu SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  PhienBan INT UNSIGNED NOT NULL DEFAULT 1,
  CapNhatLuc DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (LoaiPhongID, NgayLuuTru),
  KEY IX_TonPhongNgay_Ngay (NgayLuuTru, LoaiPhongID),
  CONSTRAINT FK_TonPhongNgay_Phong FOREIGN KEY (LoaiPhongID) REFERENCES LoaiPhong(LoaiPhongID),
  CONSTRAINT CK_TonPhongNgay_SoLuong CHECK (SoLuongDaGiu <= TongSoLuong),
  CONSTRAINT CK_TonPhongNgay_PhienBan CHECK (PhienBan >= 1)
) ENGINE=InnoDB;

CREATE TABLE XemTruocDatCho (
  XemTruocDatChoID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  TokenHash CHAR(64) NOT NULL,
  KhachHangID BIGINT UNSIGNED NOT NULL,
  CoSoLuuTruID BIGINT UNSIGNED NOT NULL,
  NgayNhanPhong DATE NOT NULL,
  NgayTraPhong DATE NOT NULL,
  TienTe CHAR(3) NOT NULL DEFAULT 'VND',
  TongTien DECIMAL(14,2) NOT NULL,
  SoTienTraNgay DECIMAL(14,2) NOT NULL DEFAULT 0,
  SoTienTraTaiCoSo DECIMAL(14,2) NOT NULL DEFAULT 0,
  PhanBoJSON JSON NOT NULL,
  Fingerprint CHAR(64) NOT NULL,
  TrangThai VARCHAR(16) NOT NULL DEFAULT 'VALID',
  HetHanLuc DATETIME(6) NOT NULL,
  TaoLuc DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  DaDungLuc DATETIME(6) NULL,
  UNIQUE KEY UQ_XemTruoc_Token (TokenHash),
  KEY IX_XemTruoc_Khach (KhachHangID, TrangThai, HetHanLuc),
  CONSTRAINT FK_XemTruoc_Khach FOREIGN KEY (KhachHangID) REFERENCES NguoiDung(NguoiDungID),
  CONSTRAINT FK_XemTruoc_CoSo FOREIGN KEY (CoSoLuuTruID) REFERENCES CoSoLuuTru(CoSoLuuTruID),
  CONSTRAINT CK_XemTruoc_Ngay CHECK (NgayNhanPhong < NgayTraPhong),
  CONSTRAINT CK_XemTruoc_Tien CHECK (TongTien >= 0 AND SoTienTraNgay >= 0 AND SoTienTraTaiCoSo >= 0 AND TongTien = SoTienTraNgay + SoTienTraTaiCoSo),
  CONSTRAINT CK_XemTruoc_TienTe CHECK (TienTe = 'VND'),
  CONSTRAINT CK_XemTruoc_TrangThai CHECK (TrangThai IN ('VALID','USED','INVALIDATED')),
  CONSTRAINT CK_XemTruoc_DaDung CHECK ((TrangThai = 'USED' AND DaDungLuc IS NOT NULL) OR (TrangThai <> 'USED' AND DaDungLuc IS NULL))
) ENGINE=InnoDB;

CREATE TABLE DatCho (
  DatChoID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  MaDatCho VARCHAR(24) NOT NULL,
  ClientRequestID CHAR(36) NOT NULL,
  XemTruocDatChoID BIGINT UNSIGNED NOT NULL,
  KhachHangID BIGINT UNSIGNED NOT NULL,
  CoSoLuuTruID BIGINT UNSIGNED NOT NULL,
  NgayNhanPhong DATE NOT NULL,
  NgayTraPhong DATE NOT NULL,
  TenNguoiDat VARCHAR(150) NOT NULL,
  EmailNguoiDat VARCHAR(190) NOT NULL,
  DienThoaiNguoiDat VARCHAR(20) NOT NULL,
  YeuCauDacBiet VARCHAR(1000) NULL,
  ThoiDiemThanhToan VARCHAR(24) NOT NULL,
  TienTe CHAR(3) NOT NULL DEFAULT 'VND',
  TongTien DECIMAL(14,2) NOT NULL,
  TrangThai VARCHAR(24) NOT NULL,
  HetHanThanhToanLuc DATETIME(6) NULL,
  XacNhanLuc DATETIME(6) NULL,
  HoanThanhLuc DATETIME(6) NULL,
  HuyIdempotencyKey CHAR(36) NULL,
  NguoiHuyID BIGINT UNSIGNED NULL,
  HuyLuc DATETIME(6) NULL,
  LyDoHuy VARCHAR(1000) NULL,
  PhiHuy DECIMAL(14,2) NOT NULL DEFAULT 0,
  SoTienHoan DECIMAL(14,2) NOT NULL DEFAULT 0,
  TinhHuySnapshotJSON JSON NULL,
  NguoiDanhDauNoShowID BIGINT UNSIGNED NULL,
  NoShowLuc DATETIME(6) NULL,
  PhiNoShow DECIMAL(14,2) NOT NULL DEFAULT 0,
  NoShowSnapshotJSON JSON NULL,
  TaoLuc DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  CapNhatLuc DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  UNIQUE KEY UQ_DatCho_Ma (MaDatCho),
  UNIQUE KEY UQ_DatCho_ClientRequest (ClientRequestID),
  UNIQUE KEY UQ_DatCho_Preview (XemTruocDatChoID),
  UNIQUE KEY UQ_DatCho_HuyIdempotency (HuyIdempotencyKey),
  KEY IX_DatCho_Khach (KhachHangID, TaoLuc),
  KEY IX_DatCho_CoSo (CoSoLuuTruID, TrangThai, NgayNhanPhong),
  CONSTRAINT FK_DatCho_Preview FOREIGN KEY (XemTruocDatChoID) REFERENCES XemTruocDatCho(XemTruocDatChoID),
  CONSTRAINT FK_DatCho_Khach FOREIGN KEY (KhachHangID) REFERENCES NguoiDung(NguoiDungID),
  CONSTRAINT FK_DatCho_CoSo FOREIGN KEY (CoSoLuuTruID) REFERENCES CoSoLuuTru(CoSoLuuTruID),
  CONSTRAINT FK_DatCho_NguoiHuy FOREIGN KEY (NguoiHuyID) REFERENCES NguoiDung(NguoiDungID),
  CONSTRAINT FK_DatCho_NguoiNoShow FOREIGN KEY (NguoiDanhDauNoShowID) REFERENCES NguoiDung(NguoiDungID),
  CONSTRAINT CK_DatCho_Ngay CHECK (NgayNhanPhong < NgayTraPhong),
  CONSTRAINT CK_DatCho_ThanhToan CHECK (ThoiDiemThanhToan IN ('PAY_AT_PROPERTY','PAY_ONLINE')),
  CONSTRAINT CK_DatCho_Tien CHECK (TienTe = 'VND' AND TongTien >= 0 AND PhiHuy >= 0 AND SoTienHoan >= 0 AND PhiNoShow >= 0),
  CONSTRAINT CK_DatCho_TrangThai CHECK (TrangThai IN ('PENDING_PAYMENT','CONFIRMED','PAYMENT_FAILED','CANCELLED','NO_SHOW','COMPLETED')),
  CONSTRAINT CK_DatCho_HuyMetadata CHECK (
    (TrangThai = 'CANCELLED' AND HuyIdempotencyKey IS NOT NULL AND NguoiHuyID IS NOT NULL AND HuyLuc IS NOT NULL AND LyDoHuy IS NOT NULL AND TinhHuySnapshotJSON IS NOT NULL) OR
    (TrangThai <> 'CANCELLED' AND HuyIdempotencyKey IS NULL AND NguoiHuyID IS NULL AND HuyLuc IS NULL AND LyDoHuy IS NULL AND PhiHuy = 0 AND SoTienHoan = 0 AND TinhHuySnapshotJSON IS NULL)
  ),
  CONSTRAINT CK_DatCho_NoShowMetadata CHECK (
    (TrangThai = 'NO_SHOW' AND NguoiDanhDauNoShowID IS NOT NULL AND NoShowLuc IS NOT NULL AND NoShowSnapshotJSON IS NOT NULL) OR
    (TrangThai <> 'NO_SHOW' AND NguoiDanhDauNoShowID IS NULL AND NoShowLuc IS NULL AND PhiNoShow = 0 AND NoShowSnapshotJSON IS NULL)
  )
) ENGINE=InnoDB;

CREATE TABLE HangMucDatCho (
  HangMucDatChoID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  DatChoID BIGINT UNSIGNED NOT NULL,
  SanPhamPhongID BIGINT UNSIGNED NOT NULL,
  LoaiPhongID BIGINT UNSIGNED NOT NULL,
  ThuTuPhong SMALLINT UNSIGNED NOT NULL,
  TenLoaiPhongSnapshot VARCHAR(150) NOT NULL,
  TenSanPhamSnapshot VARCHAR(150) NOT NULL,
