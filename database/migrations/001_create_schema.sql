-- Mini OTA nhiều cơ sở lưu trú - schema MVP 22 bảng.
-- Mục tiêu: MySQL 8.x và MariaDB 10.4.x, utf8mb4, InnoDB.

SET NAMES utf8mb4;
CREATE DATABASE IF NOT EXISTS hotel_booking CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE hotel_booking;
SET FOREIGN_KEY_CHECKS = 0;

-- Chỉ xóa các bảng của ứng dụng trong database chuyên biệt; không DROP DATABASE.
DROP TABLE IF EXISTS NhatKyHeThong, DanhGia, YeuCauHuyMienPhi, ThanhToan,
  GiuTonPhongDem, GiaDemDatCho, HangMucDatCho, DatCho, XemTruocDatCho,
  TonPhongNgay, KhuyenMai, GiaPhongNgay, SanPhamPhong, ChinhSachHuy,
  LoaiPhongTienNghi, CoSoTienNghi, LoaiPhong, CoSoLuuTru, TienNghi,
  ThanhVienDoiTac, ToChucDoiTac, NguoiDung;

-- Dọn các bảng của schema 38 bảng cũ nếu đang nâng cấp tại chỗ.
DROP TABLE IF EXISTS BoNhoDemGooglePlaces, DoiChieuGooglePlaces, ThongBao,
  HoanTien, LanThanhToan, DieuChinhDatCho, KhachLuuTru, XemTruocHangMuc,
  KhuyenMaiSanPham, GoiGia, GoiBuaAn, ThuePhiCoSo, AnhLoaiPhong, AnhCoSo,
  LoaiCoSo, ThanhPho;

CREATE TABLE NguoiDung (
  NguoiDungID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  MaNguoiDung VARCHAR(24) NOT NULL,
  HoTen VARCHAR(150) NOT NULL,
  Email VARCHAR(190) NOT NULL,
  SoDienThoai VARCHAR(20) NULL,
  MatKhauHash VARCHAR(255) NOT NULL,
  VaiTro VARCHAR(16) NOT NULL,
  TrangThai VARCHAR(16) NOT NULL DEFAULT 'HOAT_DONG',
  TaoLuc DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  CapNhatLuc DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  UNIQUE KEY UQ_NguoiDung_Ma (MaNguoiDung),
  UNIQUE KEY UQ_NguoiDung_Email (Email),
  CONSTRAINT CK_NguoiDung_VaiTro CHECK (VaiTro IN ('CUSTOMER','PARTNER','ADMIN')),
  CONSTRAINT CK_NguoiDung_TrangThai CHECK (TrangThai IN ('HOAT_DONG','KHOA'))
) ENGINE=InnoDB;

CREATE TABLE ToChucDoiTac (
  ToChucDoiTacID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  MaToChuc VARCHAR(24) NOT NULL,
  TenToChuc VARCHAR(190) NOT NULL,
  EmailLienHe VARCHAR(190) NOT NULL,
  SoDienThoai VARCHAR(20) NULL,
  TrangThai VARCHAR(16) NOT NULL DEFAULT 'HOAT_DONG',
  TaoLuc DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  UNIQUE KEY UQ_ToChuc_Ma (MaToChuc),
  CONSTRAINT CK_ToChuc_TrangThai CHECK (TrangThai IN ('HOAT_DONG','TAM_KHOA'))
) ENGINE=InnoDB;

CREATE TABLE ThanhVienDoiTac (
  ToChucDoiTacID BIGINT UNSIGNED NOT NULL,
  NguoiDungID BIGINT UNSIGNED NOT NULL,
  LaChuSoHuu TINYINT(1) NOT NULL DEFAULT 0,
  TaoLuc DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (ToChucDoiTacID, NguoiDungID),
  UNIQUE KEY UQ_ThanhVien_NguoiDung (NguoiDungID),
  CONSTRAINT FK_ThanhVien_ToChuc FOREIGN KEY (ToChucDoiTacID) REFERENCES ToChucDoiTac(ToChucDoiTacID),
  CONSTRAINT FK_ThanhVien_NguoiDung FOREIGN KEY (NguoiDungID) REFERENCES NguoiDung(NguoiDungID)
) ENGINE=InnoDB;

CREATE TABLE TienNghi (
  TienNghiID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  MaTienNghi VARCHAR(40) NOT NULL,
  TenTienNghi VARCHAR(120) NOT NULL,
  PhamVi VARCHAR(12) NOT NULL,
  TrangThai VARCHAR(16) NOT NULL DEFAULT 'HOAT_DONG',
  UNIQUE KEY UQ_TienNghi_Ma (MaTienNghi),
  CONSTRAINT CK_TienNghi_PhamVi CHECK (PhamVi IN ('PROPERTY','ROOM')),
  CONSTRAINT CK_TienNghi_TrangThai CHECK (TrangThai IN ('HOAT_DONG','NGUNG'))
) ENGINE=InnoDB;

CREATE TABLE CoSoLuuTru (
  CoSoLuuTruID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  MaCoSo VARCHAR(24) NOT NULL,
  ToChucDoiTacID BIGINT UNSIGNED NOT NULL,
  MaThanhPho CHAR(3) NOT NULL DEFAULT 'HCM',
  LoaiCoSo VARCHAR(20) NOT NULL,
  TenCoSo VARCHAR(190) NOT NULL,
  TenTrongNguon VARCHAR(255) NOT NULL,
  NguonTen VARCHAR(80) NOT NULL,
  MaBanGhiNguon VARCHAR(80) NOT NULL,
  Slug VARCHAR(220) NOT NULL,
  DiaChi VARCHAR(500) NOT NULL,
  NguonDiaChi VARCHAR(80) NOT NULL,
  DiaChiXacMinhLuc DATETIME(6) NOT NULL,
  MoTa TEXT NULL,
  AnhJSON JSON NOT NULL,
  GooglePlaceID VARCHAR(255) NULL,
  GoogleMatchStatus VARCHAR(16) NOT NULL DEFAULT 'NOT_CHECKED',
  GoogleVerifiedAt DATETIME(6) NULL,
  ViDo DECIMAL(10,7) NULL,
  KinhDo DECIMAL(10,7) NULL,
  NguonToaDo VARCHAR(40) NULL,
  ToaDoXacMinhLuc DATETIME(6) NULL,
  TrangThaiDoiChieu VARCHAR(32) NOT NULL,
  DuongDanBanDo VARCHAR(1000) NULL,
  SoSao DECIMAL(2,1) NULL,
  TyLeThue DECIMAL(5,2) NOT NULL DEFAULT 0,
  ThueDaBaoGom TINYINT(1) NOT NULL DEFAULT 1,
  TyLePhiDichVu DECIMAL(5,2) NOT NULL DEFAULT 0,
  PhiDichVuDaBaoGom TINYINT(1) NOT NULL DEFAULT 1,
  GioNhanPhong TIME NOT NULL DEFAULT '14:00:00',
  GioTraPhong TIME NOT NULL DEFAULT '12:00:00',
  MuiGio VARCHAR(64) NOT NULL DEFAULT 'Asia/Ho_Chi_Minh',
  TrangThai VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
  NguoiDuyetID BIGINT UNSIGNED NULL,
  DuyetLuc DATETIME(6) NULL,
  GhiChuDuyet VARCHAR(1000) NULL,
  TaoLuc DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  CapNhatLuc DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  UNIQUE KEY UQ_CoSo_Ma (MaCoSo),
  UNIQUE KEY UQ_CoSo_Slug (Slug),
  UNIQUE KEY UQ_CoSo_Nguon (NguonTen, MaBanGhiNguon),
  UNIQUE KEY UQ_CoSo_GooglePlace (GooglePlaceID),
  KEY IX_CoSo_TimKiem (MaThanhPho, TrangThai, LoaiCoSo),
  KEY IX_CoSo_ToChuc (ToChucDoiTacID, TrangThai),
  CONSTRAINT FK_CoSo_ToChuc FOREIGN KEY (ToChucDoiTacID) REFERENCES ToChucDoiTac(ToChucDoiTacID),
  CONSTRAINT FK_CoSo_NguoiDuyet FOREIGN KEY (NguoiDuyetID) REFERENCES NguoiDung(NguoiDungID),
  CONSTRAINT CK_CoSo_ThanhPho CHECK (MaThanhPho = 'HCM'),
  CONSTRAINT CK_CoSo_Loai CHECK (LoaiCoSo IN ('HOTEL','RESORT','APARTMENT','VILLA','HOSTEL','GUEST_HOUSE')),
  CONSTRAINT CK_CoSo_GoogleStatus CHECK (GoogleMatchStatus IN ('NOT_CHECKED','MATCHED','AMBIGUOUS','NOT_FOUND')),
  CONSTRAINT CK_CoSo_GoogleMetadata CHECK (
    (GoogleMatchStatus = 'NOT_CHECKED' AND GooglePlaceID IS NULL AND GoogleVerifiedAt IS NULL) OR
    (GoogleMatchStatus = 'MATCHED' AND GooglePlaceID IS NOT NULL AND GoogleVerifiedAt IS NOT NULL) OR
    (GoogleMatchStatus IN ('AMBIGUOUS','NOT_FOUND') AND GooglePlaceID IS NULL AND GoogleVerifiedAt IS NOT NULL)
  ),
  CONSTRAINT CK_CoSo_ToaDo CHECK (
    (ViDo IS NULL AND KinhDo IS NULL AND NguonToaDo IS NULL AND ToaDoXacMinhLuc IS NULL) OR
    (ViDo IS NOT NULL AND KinhDo IS NOT NULL AND NguonToaDo IS NOT NULL AND ToaDoXacMinhLuc IS NOT NULL
      AND ViDo BETWEEN -90 AND 90 AND KinhDo BETWEEN -180 AND 180)
  ),
  CONSTRAINT CK_CoSo_Sao CHECK (SoSao IS NULL OR SoSao BETWEEN 0 AND 5),
  CONSTRAINT CK_CoSo_ThuePhi CHECK (TyLeThue BETWEEN 0 AND 100 AND TyLePhiDichVu BETWEEN 0 AND 100),
  CONSTRAINT CK_CoSo_TrangThai CHECK (TrangThai IN ('DRAFT','PENDING_REVIEW','ACTIVE','REJECTED','SUSPENDED')),
  CONSTRAINT CK_CoSo_Duyet CHECK (
    (TrangThai IN ('ACTIVE','REJECTED','SUSPENDED') AND NguoiDuyetID IS NOT NULL AND DuyetLuc IS NOT NULL) OR
    (TrangThai IN ('DRAFT','PENDING_REVIEW') AND NguoiDuyetID IS NULL AND DuyetLuc IS NULL)
  )
) ENGINE=InnoDB;

CREATE TABLE LoaiPhong (
  LoaiPhongID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  CoSoLuuTruID BIGINT UNSIGNED NOT NULL,
  MaLoaiPhong VARCHAR(24) NOT NULL,
  TenLoaiPhong VARCHAR(150) NOT NULL,
