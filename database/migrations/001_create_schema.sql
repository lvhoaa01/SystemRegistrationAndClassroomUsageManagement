  CONSTRAINT CK_ChinhSachHuy_NoShow CHECK (TyLePhatNoShow BETWEEN 0 AND 100),
  CONSTRAINT CK_ChinhSachHuy_TrangThai CHECK (TrangThai IN ('ACTIVE','INACTIVE'))
) ENGINE=InnoDB;

CREATE TABLE SanPhamPhong (
  SanPhamPhongID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  LoaiPhongID BIGINT UNSIGNED NOT NULL,
  ChinhSachHuyID BIGINT UNSIGNED NOT NULL,
  MaSanPham VARCHAR(24) NOT NULL,
  TenSanPham VARCHAR(150) NOT NULL,
  LoaiBuaAn VARCHAR(24) NOT NULL,
  ThoiDiemThanhToan VARCHAR(24) NOT NULL,
