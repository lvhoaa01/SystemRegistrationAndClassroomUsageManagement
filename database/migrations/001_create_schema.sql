  SoKhachToiDa SMALLINT UNSIGNED NOT NULL,
  SoNguoiLonToiDa SMALLINT UNSIGNED NOT NULL,
  SoTreEmToiDa SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  CauHinhGiuongJSON JSON NOT NULL,
  DienTichM2 DECIMAL(7,2) NULL,
  ChoPhepHutThuoc TINYINT(1) NOT NULL DEFAULT 0,
  AnhJSON JSON NOT NULL,
  TrangThai VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
  TaoLuc DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  CapNhatLuc DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
