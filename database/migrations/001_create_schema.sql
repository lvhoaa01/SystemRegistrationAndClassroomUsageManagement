CREATE TABLE SlotPhong (
  PhongID BIGINT UNSIGNED NOT NULL,
  Ngay DATE NOT NULL,
  SoTiet TINYINT UNSIGNED NOT NULL,
  LoaiNguon ENUM('LICH_CHINH_THUC','PHIEU_DAT_PHONG') NOT NULL,
  LichChinhThucID BIGINT UNSIGNED NULL,
  PhieuDatPhongID BIGINT UNSIGNED NULL,
  TaoLuc DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (PhongID, Ngay, SoTiet),
  CONSTRAINT fk_slot_phong FOREIGN KEY (PhongID) REFERENCES Phong(PhongID) ON DELETE RESTRICT,
  CONSTRAINT fk_slot_lich FOREIGN KEY (LichChinhThucID) REFERENCES LichChinhThuc(LichChinhThucID) ON DELETE RESTRICT,
  CONSTRAINT fk_slot_phieu FOREIGN KEY (PhieuDatPhongID) REFERENCES PhieuDatPhong(PhieuDatPhongID) ON DELETE RESTRICT,
  CONSTRAINT ck_slot_tiet CHECK (SoTiet BETWEEN 1 AND 13),
  CONSTRAINT ck_slot_nguon CHECK (
    (LoaiNguon = 'LICH_CHINH_THUC' AND LichChinhThucID IS NOT NULL AND PhieuDatPhongID IS NULL)
    OR (LoaiNguon = 'PHIEU_DAT_PHONG' AND PhieuDatPhongID IS NOT NULL AND LichChinhThucID IS NULL)
  ),
  INDEX idx_slot_ngay (Ngay, SoTiet, PhongID),
  INDEX idx_slot_lich (LichChinhThucID),
  INDEX idx_slot_phieu (PhieuDatPhongID)
) ENGINE=InnoDB;

