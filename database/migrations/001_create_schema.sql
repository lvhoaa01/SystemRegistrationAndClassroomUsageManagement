  CONSTRAINT CK_ThanhToan_TaiCoSo CHECK (
    ThoiDiemThanhToan <> 'PAY_AT_PROPERTY' OR
    (TrangThai = 'NOT_TRACKED' AND DaThanhToan = 0 AND DaHoan = 0 AND Provider IS NULL AND IdempotencyKey IS NULL AND ProviderReference IS NULL AND SoLanThu = 0 AND MaLoiCuoi IS NULL AND XuLyLuc IS NULL AND HoanTienIdempotencyKey IS NULL AND TrangThaiHoanTien = 'NONE' AND ProviderRefundReference IS NULL AND LyDoHoanTien IS NULL AND HoanTienHoanTatLuc IS NULL)
  ),
  CONSTRAINT CK_ThanhToan_Online CHECK (
    ThoiDiemThanhToan <> 'PAY_ONLINE' OR
    (TrangThai IN ('PROCESSING','PAID','FAILED') AND Provider IS NOT NULL AND IdempotencyKey IS NOT NULL AND SoLanThu > 0)
  ),
  CONSTRAINT CK_ThanhToan_HoanMetadata CHECK (
    (TrangThaiHoanTien = 'NONE' AND DaHoan = 0 AND HoanTienIdempotencyKey IS NULL AND ProviderRefundReference IS NULL AND LyDoHoanTien IS NULL AND HoanTienHoanTatLuc IS NULL) OR
    (TrangThaiHoanTien IN ('PENDING','FAILED') AND HoanTienIdempotencyKey IS NOT NULL AND LyDoHoanTien IS NOT NULL AND HoanTienHoanTatLuc IS NULL) OR
    (TrangThaiHoanTien = 'SUCCEEDED' AND DaHoan > 0 AND HoanTienIdempotencyKey IS NOT NULL AND ProviderRefundReference IS NOT NULL AND LyDoHoanTien IS NOT NULL AND HoanTienHoanTatLuc IS NOT NULL)
  )
) ENGINE=InnoDB;

