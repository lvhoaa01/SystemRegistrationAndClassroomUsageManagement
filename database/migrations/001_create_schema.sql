CREATE TABLE ChinhSachHuy (
  ChinhSachHuyID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  CoSoLuuTruID BIGINT UNSIGNED NOT NULL,
  MaChinhSach VARCHAR(24) NOT NULL,
  TenChinhSach VARCHAR(150) NOT NULL,
  LoaiChinhSach VARCHAR(20) NOT NULL,
  SoGioHuyMienPhi SMALLINT UNSIGNED NULL,
  LoaiPhat VARCHAR(20) NOT NULL,
  GiaTriPhat DECIMAL(12,2) NOT NULL,
  TyLePhatNoShow DECIMAL(5,2) NOT NULL DEFAULT 100,
  TrangThai VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
